const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
const script=html.split('<script>')[1].split('</script>')[0];
new vm.Script(script);
const context=vm.createContext({});
vm.runInContext(script.split('let reports, votes={}')[0]+'\nthis.api={summarize,validReport,seed,WINDOW_MS};',context);
const {summarize,validReport,seed,WINDOW_MS}=context.api,now=100000000;
const report=(social,energy,crowd,age)=>({venue_id:'V001',social_vibe:social,energy_level:energy,crowd_level:crowd,created_at:now-age});
assert.equal(summarize([], 'V001',now).social,null);
assert.equal(summarize([report(8,6,'Lively',1)],'V001',now).crowd,null);
let result=summarize([report(8,6,'Lively',1),report(9,7,'Packed',2),report(7,8,'Lively',3)],'V001',now);
assert.equal(result.social,8);assert.equal(result.energy,7);assert.equal(result.crowd,'Lively');assert.equal(result.total_social,24);
result=summarize([report(8,6,'Quiet',1),report(9,7,'Packed',2),report(7,8,'Lively',3)],'V001',now);assert.equal(result.crowd,'Quiet');
result=summarize([report(8,6,'Lively',WINDOW_MS),report(9,7,'Packed',WINDOW_MS+1),report(7,8,'Lively',-1)],'V001',now);assert.equal(result.count,0);
assert.equal(validReport(report(11,6,'Lively',1)),false);assert.equal(validReport(report(1.5,6,'Lively',1)),false);assert.equal(validReport(report(8,6,'Unknown',1)),false);
const bad=report(8,6,'Quiet',1);bad.venue_id='fake';assert.equal(validReport(bad),false);
assert.equal(summarize(seed(now),'V004',now).social,null);
assert.equal(summarize(seed(now),'V001',now+WINDOW_MS).social,null);
console.log('PASS: script syntax, score averages, minimum reports, deterministic ties, expiration boundary, future reports, invalid scores, unknown venues and fixture expiry.');
